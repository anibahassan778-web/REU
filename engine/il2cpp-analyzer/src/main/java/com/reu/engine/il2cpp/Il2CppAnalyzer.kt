package com.reu.engine.il2cpp

import com.reu.core.common.DataProvenance
import com.reu.engine.elf.ElfAnalysisReport
import com.reu.engine.elf.ElfAnalyzer
import com.reu.engine.metadata.GlobalMetadataParser
import com.reu.engine.metadata.Il2CppMetadataReport
import java.io.File
import kotlinx.serialization.Serializable

@Serializable
data class Il2CppDummyClass(
  val namespaceName: String,
  val className: String,
  val tokenHex: String,
  val fieldNames: List<String>,
  val methodNames: List<String>,
  val generatedDummyCs: String,
)

@Serializable
data class Il2CppPipelineReport(
  val metadataReport: Il2CppMetadataReport,
  val elfReport: ElfAnalysisReport?,
  val dummyClasses: List<Il2CppDummyClass>,
  val limitations: List<String>,
)

class Il2CppAnalyzer(
  private val metadataParser: GlobalMetadataParser = GlobalMetadataParser(),
  private val elfAnalyzer: ElfAnalyzer = ElfAnalyzer(),
) {
  fun analyze(metadataFile: File, libIl2CppSo: File? = null): Il2CppPipelineReport {
    val meta = metadataParser.parse(metadataFile)
    val elf = libIl2CppSo?.takeIf { it.exists() }?.let { elfAnalyzer.analyze(it) }

    val dummyClasses =
      if (meta.valid) {
        meta.types.take(300).map { t ->
          val typeMethods =
            if (t.methodStart >= 0 && t.methodCount > 0) {
              (t.methodStart until minOf(meta.methods.size, t.methodStart + t.methodCount)).map {
                meta.methods[it].name
              }
            } else {
              emptyList()
            }
          val typeFields =
            if (t.fieldStart >= 0 && t.fieldCount > 0) {
              (t.fieldStart until minOf(meta.fields.size, t.fieldStart + t.fieldCount)).map {
                meta.fields[it].name
              }
            } else {
              emptyList()
            }
          val cs = buildDummyCSharp(t.namespaceName, t.typeName, t.token, typeFields, typeMethods)
          Il2CppDummyClass(
            namespaceName = t.namespaceName,
            className = t.typeName,
            tokenHex = "0x" + t.token.toString(16),
            fieldNames = typeFields,
            methodNames = typeMethods,
            generatedDummyCs = cs,
          )
        }
      } else {
        emptyList()
      }

    val limitations =
      listOf(
        "IL2CPP compiles C# IL to native AOT ARM64/ARMv7 machine code in libil2cpp.so.",
        "global-metadata.dat preserves type definitions, namespaces, method signatures, and field names.",
        "Original C# method bodies are NOT stored in global-metadata.dat and cannot be restored verbatim without native machine-code decompilation.",
      )

    return Il2CppPipelineReport(
      metadataReport = meta,
      elfReport = elf,
      dummyClasses = dummyClasses,
      limitations = limitations,
    )
  }

  private fun buildDummyCSharp(
    ns: String,
    cls: String,
    token: Long,
    fields: List<String>,
    methods: List<String>,
  ): String {
    val sb = StringBuilder()
    sb.appendLine("// [IL2CPP DUMMY SIGNATURE STUB — Generated by REU Il2CppAnalyzer]")
    sb.appendLine("// Provenance: ${DataProvenance.DECOMPILED_RECONSTRUCTED.name} (Signatures) / ${DataProvenance.MISSING_UNRECOVERABLE.name} (Bodies)")
    sb.appendLine("// Metadata Token: 0x${token.toString(16)}")
    if (ns.isNotBlank()) {
      sb.appendLine("namespace $ns")
      sb.appendLine("{")
    }
    val indent = if (ns.isNotBlank()) "    " else ""
    sb.appendLine("${indent}public class $cls")
    sb.appendLine("${indent}{")
    fields.forEach { f -> sb.appendLine("${indent}    public object $f; // Recovered field name") }
    methods.forEach { m ->
      sb.appendLine("${indent}    public void $m()")
      sb.appendLine("${indent}    {")
      sb.appendLine("${indent}        // Native implementation resides in libil2cpp.so; original C# body unavailable.")
      sb.appendLine("${indent}    }")
    }
    sb.appendLine("${indent}}")
    if (ns.isNotBlank()) sb.appendLine("}")
    return sb.toString()
  }
}
